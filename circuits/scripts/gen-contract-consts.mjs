// Emit contracts/xpr-conf-tsc/assembly/consts.ts: field modulus, curve params, INF, and the
// table 2^i·G for i in 0..31 (for computing v·G of a public 32-bit chunk in-contract).
import { buildBabyjub } from "circomlibjs";
import { writeFileSync } from "node:fs";
const bj = await buildBabyjub(); const F = bj.F;
const hex = (n) => "0x" + BigInt(n).toString(16).padStart(64, "0");
const bytes = (n) => { const h = BigInt(n).toString(16).padStart(64, "0"); return "[" + h.match(/../g).map((b) => "0x" + b).join(",") + "]"; };
const pts = []; let cur = bj.Base8;
for (let i = 0; i < 32; i++) { pts.push([F.toObject(cur[0]), F.toObject(cur[1])]); cur = bj.addPoint(cur, cur); }
const out = `// GENERATED by circuits/scripts/gen-contract-consts.mjs — do not edit.
// Baby Jubjub over the bn254 scalar field (big-endian 32-byte constants).
export const P_BE: u8[] = ${bytes(F.p)};          // field modulus p
export const A_BE: u8[] = ${bytes(F.toObject(bj.A))};          // curve a = 168700
export const D_BE: u8[] = ${bytes(F.toObject(bj.D))};          // curve d = 168696
export const ONE_BE: u8[] = ${bytes(1n)};
export const PM2_BE: u8[] = ${bytes(F.p - 2n)};        // p - 2 (for inversion via modExp)
/** 2^i * G, i = 0..31, as [x, y] big-endian 32-byte words */
export const G_POW2_X: u8[][] = [
${pts.map((p) => "  " + bytes(p[0]) + ",").join("\n")}
];
export const G_POW2_Y: u8[][] = [
${pts.map((p) => "  " + bytes(p[1]) + ",").join("\n")}
];
`;
writeFileSync("../contracts/xpr-conf-tsc/assembly/consts.ts", out);
console.log("wrote contracts/xpr-conf-tsc/assembly/consts.ts");
