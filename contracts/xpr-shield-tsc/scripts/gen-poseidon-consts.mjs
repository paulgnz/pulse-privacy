// Emits assembly/poseidon_consts.ts: circomlib's optimised Poseidon constants for t=3 and t=7,
// pre-converted to Montgomery form (x·R mod r, R = 2^256) as little-endian 32-bit limbs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const HERE = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(HERE, "../../../circuits/node_modules/circomlibjs/src/poseidon_constants_opt.json"), "utf8"));
const r = 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001n;
const R = 1n << 256n;
const mont = (x) => ((BigInt(x) % r) * R) % r;
const limbs = (x) => { const out = []; for (let i = 0; i < 8; i++) out.push(Number((x >> BigInt(32 * i)) & 0xffffffffn)); return out; };
const flat = (arr) => arr.flat(Infinity).map((x) => limbs(mont(x))).flat();
let out = "// generated by scripts/gen-poseidon-consts.mjs; do not edit\n";
const emit = (name, values) => { out += `export const ${name}: u32[] = [${values.join(",")}];\n`; };
for (const t of [3, 7]) {
  const i = t - 2;
  emit(`C${t}`, flat(src.C[i]));
  emit(`S${t}`, flat(src.S[i]));
  emit(`M${t}`, flat(src.M[i]));   // M[j][i] row-major as stored
  emit(`P${t}`, flat(src.P[i]));
}
// field constants
emit("R2", limbs((R * R) % r));           // for conversion into Montgomery form
emit("MODULUS", limbs(r));
const inv = (a, m) => { let [g, x, y] = [a, 1n, 0n], [g2, x2, y2] = [m, 0n, 1n]; while (g2) { const q = g / g2; [g, g2] = [g2, g - q * g2]; [x, x2] = [x2, x - q * x2]; [y, y2] = [y2, y - q * y2]; } return ((x % m) + m) % m; };
const n0inv = (R - inv(r, 1n << 32n)) & 0xffffffffn; // -r^{-1} mod 2^32
out += `export const N0INV: u32 = ${n0inv};\n`;
writeFileSync(join(HERE, "../assembly/poseidon_consts.ts"), out);
console.log("wrote assembly/poseidon_consts.ts", out.length, "bytes; N0INV =", n0inv.toString(16));

// zero chain for the Merkle tree: Z[0] = 0, Z[i+1] = Poseidon(Z[i], Z[i]), depth 20 → 21 entries
const { buildPoseidon } = await import(join(HERE, "../../../circuits/node_modules/circomlibjs/main.js"));
const poseidon = await buildPoseidon();
const zs = [0n];
for (let i = 0; i < 20; i++) zs.push(poseidon.F.toObject(poseidon([poseidon.F.e(zs[i]), poseidon.F.e(zs[i])])));
let z = `export const ZEROS: u32[] = [${zs.map((x) => limbs(mont(x))).flat().join(",")}];\n`;
writeFileSync(join(HERE, "../assembly/poseidon_consts.ts"), out + z);
console.log("appended ZEROS[21]; Z[20] =", zs[20].toString(16));
